package watermark

import (
	"bytes"
	"encoding/binary"
	"fmt"
	"strings"
	"unicode/utf16"
)

// JPEG 隐式标识：写入 EXIF（APP1）与 XMP（APP1）两个元数据段。
//
// 为什么两套都写：
//   - EXIF 是老牌通用字段，Windows 资源管理器、手机相册、多数看图工具都能读；
//   - XMP 的 Iptc4xmpExt:DigitalSourceType 是 IPTC 定义的「AI 生成」国际标准取值，
//     内容平台的自动检测普遍认这个字段，缺了它容易被判为未标识。

var (
	jpegSOI  = []byte{0xFF, 0xD8}
	jpegAPP0 = []byte{0xFF, 0xE0}
	jpegAPP1 = []byte{0xFF, 0xE1}
	jpegSOS  = []byte{0xFF, 0xDA}
	jpegEOI  = []byte{0xFF, 0xD9}
)

// XMP 标识：IPTC 数字来源类型中表示「经训练的算法生成媒体」的标准 URI
const iptcDigitalSourceType = "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia"

// writeJPEGMeta 把生成标识写入 JPEG 的 EXIF 与 XMP 段。
// 不解码像素，只重排 segment，画质无损。
func writeJPEGMeta(data []byte, cfg Config) ([]byte, error) {
	if len(data) < 4 || !bytes.Equal(data[:2], jpegSOI) {
		return nil, fmt.Errorf("不是合法的 JPEG")
	}

	exifSeg := buildAPP1Segment(exifPayload(cfg))
	xmpSeg := buildAPP1Segment(xmpPayload(cfg))

	var out bytes.Buffer
	out.Write(jpegSOI)

	pos := 2
	wroteInsert := false
	for pos+4 <= len(data) {
		marker := data[pos : pos+2]
		if !bytes.Equal(marker, []byte{0xFF, 0xFF}) && marker[0] != 0xFF {
			break // 结构异常，停止解析
		}
		// 跳过填充字节
		m := data[pos+1]
		if m == 0xFF {
			out.WriteByte(0xFF)
			pos++
			continue
		}

		if m == 0xD8 {
			pos += 2
			continue
		}
		if m == 0xDA { // SOS，后面是压缩数据，不再解析
			if !wroteInsert {
				out.Write(exifSeg)
				out.Write(xmpSeg)
				wroteInsert = true
			}
			out.Write(data[pos:])
			return out.Bytes(), nil
		}

		segLen := int(binary.BigEndian.Uint16(data[pos+2 : pos+4]))
		end := pos + 2 + segLen
		if segLen < 2 || end > len(data) {
			return nil, fmt.Errorf("JPEG segment 越界")
		}

		// APP0(JFIF) 之后是最合适的插入点：既保留了 JFIF 该在的位置，
		// 又能让 EXIF/XMP 紧跟在文件头附近，符合大多数工具的预期。
		if !wroteInsert && !bytes.Equal(marker, jpegAPP0) {
			out.Write(exifSeg)
			out.Write(xmpSeg)
			wroteInsert = true
		}

		payload := data[pos+4 : end]
		if bytes.Equal(marker, jpegAPP1) && (isExifPayload(payload) || isXMPPayload(payload)) {
			// 丢弃旧的 EXIF/XMP，用新生成的替换，避免出现两个同名段
			pos = end
			continue
		}

		out.Write(data[pos:end])
		pos = end
	}

	if !wroteInsert {
		out.Write(exifSeg)
		out.Write(xmpSeg)
	}
	if pos < len(data) {
		out.Write(data[pos:])
	}
	return out.Bytes(), nil
}

// buildAPP1Segment 组装一个完整的 APP1 segment（含 marker 与长度）。
func buildAPP1Segment(payload []byte) []byte {
	var b bytes.Buffer
	b.Write(jpegAPP1)
	var lenBuf [2]byte
	// 长度字段包含自身 2 字节
	binary.BigEndian.PutUint16(lenBuf[:], uint16(len(payload)+2))
	b.Write(lenBuf[:])
	b.Write(payload)
	return b.Bytes()
}

func isExifPayload(p []byte) bool {
	return len(p) >= 6 && string(p[:6]) == "Exif\x00\x00"
}

func isXMPPayload(p []byte) bool {
	return bytes.HasPrefix(p, []byte("http://ns.adobe.com/xap/1.0/\x00"))
}

// ---------- EXIF ----------

type exifEntry struct {
	tag   uint16
	typ   uint16 // 1=BYTE 2=ASCII 7=UNDEFINED
	count uint32
	value []byte
}

// exifPayload 构造 "Exif\0\0" + TIFF(小端) 结构。
//
// 注意：EXIF 的 ASCII 型字段（ImageDescription / Software / Artist / Copyright）
// 只支持 Latin-1，写中文会变成一串问号，反而让文件看起来像坏了。
// 因此这些字段统一用英文短句，中文声明放到 UserComment（UNDEFINED 型，UTF-16BE）。
func exifPayload(cfg Config) []byte {
	const desc = "AI-generated content"
	tags := []exifEntry{
		{tag: 0x010E, typ: 2, value: asciiZ(desc)},                                  // ImageDescription
		{tag: 0x0131, typ: 2, value: asciiZ(cfg.ProviderName)},                      // Software
		{tag: 0x0132, typ: 2, value: asciiZ(exifDateTime())},                        // DateTime
		{tag: 0x013B, typ: 2, value: asciiZ(cfg.ProviderName)},                      // Artist
		{tag: 0x8298, typ: 2, value: asciiZ("AI-generated by " + cfg.ProviderName)}, // Copyright
		{tag: 0x9286, typ: 7, value: userComment(cfg.DeclareText)},                  // UserComment
	}

	var buf bytes.Buffer
	buf.WriteString("Exif\x00\x00")

	// TIFF header：小端
	header := make([]byte, 8)
	header[0], header[1] = 'I', 'I'
	binary.LittleEndian.PutUint16(header[2:4], 0x2A)
	binary.LittleEndian.PutUint32(header[4:8], 8) // IFD0 紧随 header
	buf.Write(header)

	ifdSize := 2 + len(tags)*12 + 4
	dataOffset := uint32(8 + ifdSize)

	// 先算出每个 entry 的值偏移
	offsets := make([]uint32, len(tags))
	var dataBuf bytes.Buffer
	for i, t := range tags {
		if len(t.value) <= 4 {
			continue // 内联存放
		}
		// 数据区按 2 字节对齐
		if dataBuf.Len()%2 == 1 {
			dataBuf.WriteByte(0)
		}
		offsets[i] = dataOffset + uint32(dataBuf.Len())
		dataBuf.Write(t.value)
	}

	// IFD0
	var cnt [2]byte
	binary.LittleEndian.PutUint16(cnt[:], uint16(len(tags)))
	buf.Write(cnt[:])

	for i, t := range tags {
		e := make([]byte, 12)
		binary.LittleEndian.PutUint16(e[0:2], t.tag)
		binary.LittleEndian.PutUint16(e[2:4], t.typ)
		count := uint32(len(t.value))
		binary.LittleEndian.PutUint32(e[4:8], count)
		if len(t.value) <= 4 {
			copy(e[8:12], t.value)
		} else {
			binary.LittleEndian.PutUint32(e[8:12], offsets[i])
		}
		buf.Write(e)
	}
	// next IFD = 0
	buf.Write([]byte{0, 0, 0, 0})

	buf.Write(dataBuf.Bytes())
	return buf.Bytes()
}

// userComment 构造 EXIF UserComment（0x9286）。
// 规范要求：8 字节字符集前缀 + 内容；用 "UNICODE\0" 前缀时内容为 UTF-16BE，
// 这样中文声明也能被正确读出（纯 ASCII 会被大多数工具当乱码）。
func userComment(text string) []byte {
	var b bytes.Buffer
	b.WriteString("UNICODE\x00")
	for _, u := range utf16.Encode([]rune(text)) {
		var pair [2]byte
		binary.BigEndian.PutUint16(pair[:], u) // EXIF 的 UNICODE 约定为 big-endian
		b.Write(pair[:])
	}
	return b.Bytes()
}

// asciiZ 生成以 NUL 结尾的 ASCII 串（非 ASCII 字符替换为 '?'）。
func asciiZ(s string) []byte {
	var b strings.Builder
	for _, r := range s {
		if r < 128 && r >= 32 {
			b.WriteRune(r)
		} else if r == ' ' {
			b.WriteRune(r)
		} else {
			b.WriteByte('?')
		}
	}
	return append([]byte(b.String()), 0)
}

// ---------- XMP ----------

// xmpPayload 构造带 IPTC 数字来源类型的 XMP 包。
// 这里刻意不做 XML 转义以外的美化——XMP 需要是紧凑 UTF-8。
func xmpPayload(cfg Config) []byte {
	var b bytes.Buffer
	b.WriteString("http://ns.adobe.com/xap/1.0/\x00")
	b.WriteString(`<?xpacket begin="` + "\xEF\xBB\xBF" + `" id="W5M0MpCehiHzreSzNTczkc9d"?>`)
	b.WriteString(`<x:xmpmeta xmlns:x="adobe:ns:meta/">`)
	b.WriteString(`<rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">`)
	b.WriteString(`<rdf:Description rdf:about=""`)
	b.WriteString(` xmlns:dc="http://purl.org/dc/elements/1.1/"`)
	b.WriteString(` xmlns:xmp="http://ns.adobe.com/xap/1.0/"`)
	b.WriteString(` xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/"`)
	b.WriteString(` xmlns:xmpMM="http://ns.adobe.com/xap/1.0/mm/"`)
	b.WriteString(` xmp:CreatorTool="` + xmlEscape(cfg.ProviderName) + `"`)
	b.WriteString(` xmpMM:DocumentID="` + xmlEscape(cfg.ContentID()) + `"`)
	b.WriteString(` Iptc4xmpExt:DigitalSourceType="` + iptcDigitalSourceType + `">`)
	b.WriteString(`<dc:description><rdf:Alt><rdf:li xml:lang="x-default">` +
		xmlEscape(cfg.DeclareText) + `</rdf:li></rdf:Alt></dc:description>`)
	b.WriteString(`</rdf:Description></rdf:RDF></x:xmpmeta>`)
	b.WriteString(`<?xpacket end="w"?>`)
	return b.Bytes()
}

func xmlEscape(s string) string {
	r := strings.NewReplacer(
		"&", "&amp;",
		"<", "&lt;",
		">", "&gt;",
		`"`, "&quot;",
		"'", "&apos;",
	)
	return r.Replace(s)
}
